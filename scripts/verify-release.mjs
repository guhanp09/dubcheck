import { chromium } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const url = process.argv[2] || 'http://127.0.0.1:4184/';
const output = process.argv[3] || '/tmp/dubcheck-release';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: process.env.CI ? undefined : 'chrome' });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const page = await context.newPage();
const errors = [], failedRequests = [], responses = [];
page.on('pageerror', e => errors.push(e.message));
page.on('requestfailed', r => failedRequests.push({ url: r.url(), error: r.failure()?.errorText }));
page.on('response', r => { if (r.status() >= 400) responses.push({ url: r.url(), status: r.status() }); });
const response = await page.goto(url);
await page.getByRole('heading', { name: 'Every language. The same idea.' }).waitFor();
await page.screenshot({ path: `${output}/workspace.png`, fullPage: true });
await page.getByRole('radio', { name: 'Needs correction' }).check();
await page.getByLabel('Proposed dub text').fill('इस अध्ययन में 24 लोग भाग लेते हैं।');
await page.getByLabel('Reviewer', { exact: true }).fill('Release verification reviewer');
await page.getByLabel('Reason / evidence').fill('Authored sample: original 24, target 48; correct the script to 24.');
await page.getByRole('button', { name: 'Save decision', exact: true }).click();
await page.getByText('Current decision recorded').waitFor();
await page.reload();
const persisted = await page.getByLabel('Proposed dub text').inputValue() === 'इस अध्ययन में 24 लोग भाग लेते हैं।';
await page.getByRole('button', { name: 'Export handoff' }).click();
const pending = page.waitForEvent('download');
await page.getByRole('button', { name: /Corrected script · SRT/ }).click();
const download = await pending, script = await readFile(await download.path(), 'utf8');
const exported = download.suggestedFilename() === 'dubcheck-draft-hi.srt' && script.includes('24 लोग');
const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
const mobile = await mobileContext.newPage();
mobile.on('pageerror', e => errors.push(e.message));
await mobile.goto(url);
await mobile.getByRole('heading', { name: 'Every language. The same idea.' }).waitFor();
await mobile.screenshot({ path: `${output}/mobile.png`, fullPage: true });
const mobileOverflow = await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth);
const result = { checkedAt: new Date().toISOString(), url, httpStatus: response?.status(), persisted, exported, mobileOverflow, errors, failedRequests, failedResponses: responses };
await writeFile(`${output}/verification.json`, JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify(result, null, 2));
await browser.close();
if (result.httpStatus !== 200 || !persisted || !exported || mobileOverflow || errors.length || failedRequests.length || responses.length) process.exitCode = 1;
